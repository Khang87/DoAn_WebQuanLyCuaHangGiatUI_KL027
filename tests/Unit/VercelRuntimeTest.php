<?php

namespace Tests\Unit;

use App\Support\VercelRuntime;
use Illuminate\Contracts\Http\Kernel;
use Illuminate\Filesystem\Filesystem;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Blade;
use PHPUnit\Framework\Attributes\PreserveGlobalState;
use PHPUnit\Framework\Attributes\RunTestsInSeparateProcesses;
use PHPUnit\Framework\TestCase;

#[RunTestsInSeparateProcesses]
#[PreserveGlobalState(false)]
class VercelRuntimeTest extends TestCase
{
    private string $temporaryDirectory;

    protected function setUp(): void
    {
        parent::setUp();

        $this->temporaryDirectory = sys_get_temp_dir().'/sky-laundry-vercel-test-'.bin2hex(random_bytes(8));

        // Use only disposable configuration; never load the project's .env or database.
        foreach ([
            'APP_ENV' => 'testing',
            'APP_DEBUG' => 'false',
            'APP_KEY' => 'base64:'.base64_encode(str_repeat('t', 32)),
            'DB_CONNECTION' => 'sqlite',
            'DB_DATABASE' => ':memory:',
            'DB_URL' => '',
            'CACHE_STORE' => 'array',
            'SESSION_DRIVER' => 'array',
            'LOG_CHANNEL' => 'null',
            'VIETQR_BANK_BIN' => '970422',
            'VIETQR_BANK_NAME' => 'MB Bank Test',
            'VIETQR_ACCOUNT_NUMBER' => '123456789',
            'VIETQR_ACCOUNT_NAME' => 'SKY LAUNDRY TEST',
            'BEEPAY_PAYMENT_PREFIX' => 'SKY',
        ] as $name => $value) {
            $_ENV[$name] = $value;
            $_SERVER[$name] = $value;
            putenv($name.'='.$value);
        }
    }

    protected function tearDown(): void
    {
        // Both the path and prefix are generated by this test, outside the checkout.
        if (str_starts_with($this->temporaryDirectory, sys_get_temp_dir().'/sky-laundry-vercel-test-')) {
            (new Filesystem)->deleteDirectory($this->temporaryDirectory);
        }

        parent::tearDown();
    }

    public function test_cold_start_boots_and_serves_payment_config_with_fresh_writable_caches(): void
    {
        $app = require dirname(__DIR__, 2).'/bootstrap/app.php';
        $app->loadEnvironmentFrom('.env.vercel-runtime-test-does-not-exist');
        VercelRuntime::prepare($app, $this->temporaryDirectory);

        $kernel = $app->make(Kernel::class);
        $kernel->bootstrap();
        $response = $kernel->handle(Request::create('/api/v1/payment-config', 'GET', server: [
            'HTTP_ACCEPT' => 'application/json',
        ]));

        self::assertSame(200, $response->getStatusCode(), $response->getContent());
        self::assertSame([
            'enabled' => true,
            'bank_bin' => '970422',
            'bank_name' => 'MB Bank Test',
            'account_number' => '123456789',
            'account_name' => 'SKY LAUNDRY TEST',
            'payment_prefix' => 'SKY',
        ], json_decode($response->getContent(), true, flags: JSON_THROW_ON_ERROR));
        self::assertFileExists($app->getCachedServicesPath());
        self::assertFileExists($app->getCachedPackagesPath());
        self::assertStringStartsWith($this->temporaryDirectory.'/storage/', $app->getCachedServicesPath());
        self::assertTrue($app->bound('view'));
        self::assertSame('Preview OK', Blade::render('Preview {{ $label }}', ['label' => 'OK']));

        $root = $kernel->handle(Request::create('/'));
        self::assertSame(302, $root->getStatusCode());
        self::assertStringEndsWith('/login', $root->headers->get('Location'));

        $missing = $kernel->handle(Request::create('/api/v1/missing-test-route', 'GET', server: [
            'HTTP_ACCEPT' => 'application/json',
        ]));
        self::assertSame(404, $missing->getStatusCode());
        self::assertStringContainsString('application/json', $missing->headers->get('Content-Type'));
    }
}
